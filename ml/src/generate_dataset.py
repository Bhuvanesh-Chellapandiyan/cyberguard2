def generate_dataset(output_path: str = "ml/data/urls_dataset.csv"):
    """
    Combines authentic legitimate and phishing URLs into a clean CSV dataset.
    Label convention: 0 = Legitimate, 1 = Phishing
    """
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    
    rows = []
    # Add legitimate URLs
    for url in LEGITIMATE_SAMPLES:
        rows.append({"url": url.strip(), "label": 0})
    
    # Add phishing URLs
    for url in PHISHING_SAMPLES:
        rows.append({"url": url.strip(), "label": 1})
    
    # Shuffle dataset with a reproducible seed
    random.seed(42)
    random.shuffle(rows)
    
    with open(output_path, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["url", "label"])
        writer.writeheader()
        writer.writerows(rows)
        
    print(f"Dataset generated successfully at {output_path} with {len(rows)} samples.")
    legit_count = sum(1 for r in rows if r["label"] == 0)
    phish_count = sum(1 for r in rows if r["label"] == 1)
    print(f"Class distribution: Legitimate (0): {legit_count}, Phishing (1): {phish_count}")


if __name__ == "__main__":
    generate_dataset()
